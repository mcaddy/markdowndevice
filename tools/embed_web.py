#!/usr/bin/env python3
"""Embed the contents of web/ into a C header (src/web_assets.h).

Each file becomes a byte array plus an entry in web_assets[], keyed by its
URL path ("/" + filename). The HTTP server serves these directly from flash.

Usage: embed_web.py <web_dir> <output_header>
"""
import sys
import os

CTYPES = {
    ".css":  "text/css; charset=utf-8",
    ".js":   "text/javascript; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".svg":  "image/svg+xml",
    ".ico":  "image/x-icon",
    ".txt":  "text/plain; charset=utf-8",
    ".json": "application/json",
}


def c_ident(name):
    return "asset_" + "".join(ch if ch.isalnum() else "_" for ch in name)


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: embed_web.py <web_dir> <output_header>\n")
        return 1
    web_dir, out_path = sys.argv[1], sys.argv[2]

    files = sorted(
        f for f in os.listdir(web_dir)
        if os.path.isfile(os.path.join(web_dir, f)) and not f.startswith(".")
    )

    lines = []
    lines.append("/* Auto-generated by tools/embed_web.py. Do not edit. */")
    lines.append("#ifndef WEB_ASSETS_H_")
    lines.append("#define WEB_ASSETS_H_")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("  const char *path;")
    lines.append("  const char *ctype;")
    lines.append("  const unsigned char *data;")
    lines.append("  unsigned int len;")
    lines.append("} web_asset_t;")
    lines.append("")

    entries = []
    for f in files:
        ext = os.path.splitext(f)[1].lower()
        ctype = CTYPES.get(ext, "application/octet-stream")
        with open(os.path.join(web_dir, f), "rb") as fh:
            data = fh.read()
        ident = c_ident(f)
        body = ", ".join(str(b) for b in data)
        lines.append("static const unsigned char %s[] = { %s };" % (ident, body))
        entries.append((("/" + f), ctype, ident, len(data)))

    lines.append("")
    lines.append("static const web_asset_t web_assets[] = {")
    for path, ctype, ident, length in entries:
        lines.append('  { "%s", "%s", %s, %u },' % (path, ctype, ident, length))
    lines.append("};")
    lines.append("static const unsigned int web_assets_count = %u;" % len(entries))
    lines.append("")
    lines.append("#endif /* WEB_ASSETS_H_ */")

    text = "\n".join(lines) + "\n"

    # Only rewrite if changed, so we don't force rebuilds.
    old = None
    if os.path.exists(out_path):
        with open(out_path, "r", encoding="utf-8") as fh:
            old = fh.read()
    if old != text:
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(text)
        sys.stderr.write("embed_web.py: wrote %s (%d assets)\n" % (out_path, len(entries)))
    else:
        sys.stderr.write("embed_web.py: %s up to date\n" % out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
